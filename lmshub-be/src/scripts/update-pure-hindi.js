// ─────────────────────────────────────────────────────────────────────────────
// Extract English paragraph from existing HTML content
// ─────────────────────────────────────────────────────────────────────────────
function extractEnglish(content) {
  const m = content.match(/class='mb-3 text-slate-700 leading-relaxed'>([\s\S]*?)<\/p>/);
  return m ? m[1].trim() : '';
}

// ─────────────────────────────────────────────────────────────────────────────
// Process — update only video lessons that have pure Hindi translations
// ─────────────────────────────────────────────────────────────────────────────
let updatedCount = 0;
let skippedCount = 0;

for (const section of data.sections) {
  const secOrder = section.sort_order;
  const hindiForSection = pureHindi[secOrder];

  for (const lesson of section.lessons) {
    const lesOrder = lesson.sort_order;

    // Only update video lessons (title starts with "Video")
    if (!lesson.title.startsWith('Video')) {
      skippedCount++;
      continue;
    }

    if (!hindiForSection || !hindiForSection[lesOrder]) {
      console.warn(`⚠️  No Hindi translation for Section ${secOrder} / Lesson ${lesOrder} ("${lesson.title}")`);
      skippedCount++;
      continue;
    }

    const englishText = extractEnglish(lesson.content);
    if (!englishText) {
      console.warn(`⚠️  Could not extract English text for "${lesson.title}"`);
      skippedCount++;
      continue;
    }

    lesson.content = buildVideoHTML(lesson.title, englishText, hindiForSection[lesOrder]);
    updatedCount++;
    console.log(`✅  Updated: [M${secOrder}] ${lesson.title}`);
  }
}

